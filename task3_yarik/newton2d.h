#ifndef NEWTON2D_H
#define NEWTON2D_H

#include "functions2d.h"

/* ИНТЕРПОЛЯЦИОННАЯ ФОРМУЛА НЬЮТОНА ДЛЯ ФУНКЦИИ ДВУХ ПЕРЕМЕННЫХ
 * (интерполяция тензорными произведениями, см. 1.5.3).
 *
 * Базисные функции:
 *     u_i(x) = (x-x_1)(x-x_2)...(x-x_{i-1}),   i = 1..nx,
 *     v_j(y) = (y-y_1)(y-y_2)...(y-y_{j-1}),   j = 1..ny
 * (пустое произведение равно 1), базис в пространстве функций --
 * их тензорные произведения w_ij(x,y) = u_i(x) v_j(y).
 *
 * Приближающая функция:
 *     P(x,y) = sum_{i=1..nx} sum_{j=1..ny} c_ij u_i(x) v_j(y),
 * где c_ij = f[x_1,...,x_i; y_1,...,y_j] -- смешанные (двойные)
 * разделённые разности: сначала разделённые разности по x, затем по y.
 *
 * Построенный многочлен точно интерполирует f в узлах сетки:
 *     P(x_i, y_j) = f(x_i, y_j) для всех i, j.
 */

/* Узлы Чебышёва (нули многочлена Чебышёва) на отрезке [a, b]:
 *     t_i = (a+b)/2 + (b-a)/2 * cos( pi (i + 1/2) / n ),  i = 0..n-1.
 * Возвращаются по возрастанию. Именно такие узлы берутся вместо
 * равномерных, чтобы подавить эффект Рунге у краёв области. */
void make_chebyshev_nodes(int n, double a, double b, double *nodes);

/* Переупорядочение узлов в последовательность Лежа: очередным берётся
 * тот узел, который максимизирует произведение расстояний до уже
 * выбранных. Сам многочлен от порядка узлов не зависит, но разделённые
 * разности и схема Горнера в форме Ньютона при монотонном порядке узлов
 * численно неустойчивы уже при n ~ 30 (погрешности округления растут
 * лавинообразно), а при порядке Лежа остаются на уровне машинной
 * точности. Вызывается один раз после построения узлов. */
void reorder_nodes_leja(int n, double *nodes);

/* Построение коэффициентов c_ij.
 *   nx, ny   -- число узлов по x и по y (nx, ny >= 1);
 *   x_nodes  -- массив узлов по x длины nx (узлы попарно различны;
 *               порядок узлов -- это порядок формулы Ньютона);
 *   y_nodes  -- массив узлов по y длины ny (узлы попарно различны);
 *   f_values -- значения f(x_i, y_j), хранение построчное:
 *               f_values[i*ny + j] = f(x_i, y_j), длина nx*ny;
 *   coeffs   -- выходной массив длины nx*ny с коэффициентами c_ij
 *               (то же построчное хранение).
 * Возвращает 0 при успехе, -1 при ошибке (тогда coeffs[0] = NaN). */
int make_newton2d_coefficients(int nx, int ny, const double *x_nodes,
                               const double *y_nodes, const double *f_values,
                               double *coeffs);

/* Значение приближающего многочлена в точке (px, py).
 * Считается двойной схемой Горнера за O(nx*ny) действий. */
double calculate_newton2d_value(double px, double py, int nx, int ny,
                                const double *x_nodes, const double *y_nodes,
                                const double *coeffs);

/* Погрешность f(px,py) - P(px,py) в точке */
double calculate_newton2d_discrepancy(double px, double py, func2_t func,
                                      int nx, int ny, const double *x_nodes,
                                      const double *y_nodes,
                                      const double *coeffs);

#endif /* NEWTON2D_H */
