#ifndef INVERSE_H
#define INVERSE_H

/* Обратная матрица методом Гаусса с выбором главного элемента по всей матрице.
   a    - исходная матрица n x n, она портится в процессе;
   x    - сюда кладётся обратная матрица (n x n);
   col  - рабочий массив длины n;
   norm - норма матрицы a (нужна, чтобы понять, что считать нулём).
   Возвращает 0, если всё хорошо, и -1, если матрица вырождена. */
int inverse_matrix(double *a, double *x, int *col, int n, double norm);

#endif
