#!/bin/sh
#
# Проверка программы. Запуск:
#
#     sh tests.sh              - обычный прогон
#     sh tests.sh 4 2000       - 4 процесса, большая матрица 2000x2000
#
# Первый аргумент - сколько процессов брать в тестах на корректность,
# второй - размер матрицы в тестах на ускорение.

NP=${1:-2}
NBIG=${2:-2000}
EXE=./a.out
T=tests

if [ ! -x $EXE ]; then
	echo "Программа не собрана, собираю..."
	mpicc -O2 -Wall -Wextra main.c input.c output.c gauss_reverse_MPI.c -o a.out -lm || exit 1
fi

# сколько на машине быстрых ядер (для тестов на ускорение)
CORES=`sysctl -n hw.perflevel0.logicalcpu 2>/dev/null || sysctl -n hw.ncpu 2>/dev/null || nproc 2>/dev/null || echo 4`

echo
echo "================================================================"
echo " ЧАСТЬ 1. МАЛЕНЬКИЕ МАТРИЦЫ, ОТВЕТ ИЗВЕСТЕН ЗАРАНЕЕ"
echo "          (запуск на $NP процессах)"
echo "================================================================"

echo
echo "--- 1.1 Единичная матрица 3x3. Обратная к ней - она сама, Res = 0"
mpirun -np $NP $EXE 3 3 0 $T/e.txt

echo
echo "--- 1.2 Нули на диагонали: без выбора главного элемента метод бы упал"
echo "    Матрица:            Обратная должна быть:"
echo "     0 2 0                0      1/3     0"
echo "     3 0 0                1/2    0       0"
echo "     0 0 4                0      0       1/4"
mpirun -np $NP $EXE 3 3 0 $T/pivot.txt

echo
echo "--- 1.3 Несимметричная матрица с целой обратной."
echo "    Обратная должна быть в точности:"
echo "     -24   18    5"
echo "      20  -15   -4"
echo "      -5    4    1"
mpirun -np $NP $EXE 3 3 0 $T/nonsym.txt

echo
echo "--- 1.4 Матрица 4x4 из a.txt (симметричная)"
mpirun -np $NP $EXE 4 4 0 a.txt

echo
echo "--- 1.5 Вырожденная матрица (вторая строка = удвоенная первая)."
echo "    Ожидаем Res1 = -1, Res2 = -1 и НИКАКОЙ обратной матрицы"
mpirun -np $NP $EXE 3 3 0 $T/sing.txt

echo
echo "================================================================"
echo " ЧАСТЬ 2. ОШИБКИ ВВОДА - ПРОГРАММА ДОЛЖНА РУГАТЬСЯ, А НЕ ПАДАТЬ"
echo "================================================================"

echo
echo "--- 2.1 Файла нет"
mpirun -np $NP $EXE 3 3 0 $T/net_takogo_fayla.txt

echo
echo "--- 2.2 В файле буквы вместо чисел"
mpirun -np $NP $EXE 3 3 0 $T/bad.txt

echo
echo "--- 2.3 В файле меньше чисел, чем нужно"
mpirun -np $NP $EXE 3 3 0 $T/short.txt

echo
echo "--- 2.4 Неверный номер формулы (s = 7)"
mpirun -np $NP $EXE 5 5 7

echo
echo "--- 2.5 Лишний аргумент при s != 0"
mpirun -np $NP $EXE 5 5 2 lishniy.txt

echo
echo "================================================================"
echo " ЧАСТЬ 3. ФОРМУЛЫ 1, 2, 3. ЖДЁМ МАЛЕНЬКИЕ НЕВЯЗКИ"
echo "================================================================"
for s in 1 2 3; do
	echo
	echo "--- формула s = $s, n = 500"
	mpirun -np $NP $EXE 500 0 $s
done

echo
echo "================================================================"
echo " ЧАСТЬ 4. МАТРИЦА ГИЛЬБЕРТА (формула s = 4)"
echo "================================================================"
echo
echo " Это знаменитая ПЛОХО ОБУСЛОВЛЕННАЯ матрица: a(i,j) = 1/(i+j-1)."
echo " Она обратима, но её определитель чудовищно мал, и с ростом n"
echo " двойной точности перестаёт хватать. Смотри, как растёт невязка:"
echo
for n in 3 5 8 9 10; do
	echo "--- n = $n (считается, но точность тает на глазах)"
	mpirun -np $NP $EXE $n 0 4
done
echo
echo " А теперь то же самое при n >= 11. Программа честно говорит"
echo " Res1 = -1: в арифметике double матрица уже неотличима от"
echo " вырожденной (число обусловленности ~1e15), и любой ответ"
echo " был бы мусором. Это ПРАВИЛЬНОЕ поведение, а не ошибка."
echo
for n in 11 12 20 50; do
	echo "--- n = $n"
	mpirun -np $NP $EXE $n 0 4
done

echo
echo "================================================================"
echo " ЧАСТЬ 5. БОЛЬШИЕ МАТРИЦЫ: СМОТРИМ НА УСКОРЕНИЕ"
echo "          n = $NBIG, быстрых ядер на машине: $CORES"
echo "================================================================"
echo
echo " Сравнивать надо T1 - время работы самого алгоритма."
echo " (T2 - это подсчёт невязок, там другая схема обменов.)"
echo
for p in 1 2 4 8 16; do
	if [ $p -le $CORES ]; then
		echo "--- процессов: $p"
		mpirun -np $p $EXE $NBIG 0 1
	fi
done

echo
echo "================================================================"
echo " ВСЁ. Что должно было получиться:"
echo "   - в части 1 невязки Res1 и Res2 порядка 1e-14 и меньше;"
echo "   - в части 3 порядка 1e-10: матрица больше, округлений накопилось"
echo "     больше - это нормально;"
echo "   - в тесте 1.5 и в конце части 4: Res1 = -1, Res2 = -1;"
echo "   - в части 2 - понятные сообщения об ошибках, без падений;"
echo "   - в части 5 время T1 падает с ростом числа процессов."
echo "================================================================"
